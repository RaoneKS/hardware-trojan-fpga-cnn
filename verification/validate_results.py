#!/usr/bin/env python3
"""Validate the measured-run ledger without manufacturing data."""

import csv
import sys
from collections import Counter

PATH = "verification/results/runs.csv"
REQUIRED = [
    "workload_id", "trojan_id", "trojan_present", "trigger_location",
    "predicted_class", "expected_class", "detected",
    "expected_localization", "localization_code",
    "inference_cycles", "detection_cycle", "detection_latency_cycles",
]

with open(PATH, newline="") as f:
    reader = csv.DictReader(f)
    fields = reader.fieldnames or []
    missing = [x for x in REQUIRED if x not in fields]
    if missing:
        raise SystemExit("Missing columns: " + ", ".join(missing))
    rows = list(reader)

if not rows:
    print("VALID: schema present; no measured rows yet.")
    raise SystemExit(0)

def b(v):
    return str(v).strip().lower() in {"1", "true", "yes", "y"}

errors = []
for i, r in enumerate(rows, start=2):
    for k in REQUIRED:
        if not str(r.get(k, "")).strip():
            errors.append(f"row {i}: empty {k}")
    try:
        int(r["predicted_class"]); int(r["expected_class"])
        int(r["inference_cycles"]); int(r["detection_cycle"])
        int(r["detection_latency_cycles"])
    except ValueError:
        errors.append(f"row {i}: non-integer numeric field")
    if b(r["trojan_present"]) and not r["expected_localization"].strip():
        errors.append(f"row {i}: Trojan-present run needs expected_localization")
    if b(r["trojan_present"]) and not b(r["detected"]) and r["localization_code"].strip() not in {"", "NA", "nan"}:
        errors.append(f"row {i}: undetected run should not silently claim a localization")

if errors:
    print("INVALID")
    print("\n".join(errors))
    sys.exit(1)

trojan = sum(b(r["trojan_present"]) for r in rows)
healthy = len(rows) - trojan
workloads = Counter(r["workload_id"] for r in rows)
print(f"VALID: {len(rows)} measured rows")
print(f"Healthy/Trojan-present rows: {healthy}/{trojan}")
print(f"Distinct workloads: {len(workloads)}")
print("No synthetic rows are generated by this validator.")
